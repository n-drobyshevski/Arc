// Port of core/src/main/kotlin/dev/arc/ep133/text/GuideText.kt (the `sections` data)
//
// Generates web/src/core/text/guideData.ts from GuideText.kt, so the 100 guide
// entries are never retyped by hand. GuideText.kt is strictly regular after
// `val sections`: every line is `GuideSection(`, `GuideEntry(`, `listOf(`, `),`,
// `)`, a bare "string", or `combo = "string",`. Entry strings are positional
// (action, keys, source, [note]). Anything else stops the script with an error.
//
//   node scripts/gen-guide-data.mjs            write src/core/text/guideData.ts
//   node scripts/gen-guide-data.mjs --stdout   print it instead (used by the test)

import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

const KT_PATH = 'core/src/main/kotlin/dev/arc/ep133/text/GuideText.kt'
const ktFile = fileURLToPath(new URL('../../' + KT_PATH, import.meta.url))
const outFile = fileURLToPath(new URL('../src/core/text/guideData.ts', import.meta.url))

/** A Kotlin string literal with no escapes or templates, as the guide uses. */
function literal(raw, lineNo) {
  const m = /^"([^"\\$]*)"$/.exec(raw)
  if (!m) throw new Error(`GuideText.kt:${lineNo}: unsupported string literal ${raw}`)
  return m[1]
}

export function parseGuide(source) {
  const lines = source.split(/\r?\n/)
  const start = lines.findIndex((l) => l.trim() === 'val sections: List<GuideSection> = listOf(')
  if (start < 0) throw new Error('GuideText.kt: `val sections: List<GuideSection> = listOf(` not found')

  const sections = []
  // States: list (inside the sections list), section, entries, entry, done.
  let state = 'list'
  let section = null
  let entry = null
  for (let i = start + 1; i < lines.length && state !== 'done'; i++) {
    const lineNo = i + 1
    const line = lines[i].trim()
    if (line === '') continue
    const fail = () => {
      throw new Error(`GuideText.kt:${lineNo}: unexpected "${line}" (state ${state})`)
    }
    switch (state) {
      case 'list':
        if (line === 'GuideSection(') {
          section = { title: null, entries: [] }
          state = 'section'
        } else if (line === ')') state = 'done'
        else fail()
        break
      case 'section':
        if (line.startsWith('"') && line.endsWith('",') && section.title === null) {
          section.title = literal(line.slice(0, -1), lineNo)
        } else if (line === 'listOf(' && section.title !== null) state = 'entries'
        else if (line === '),' && section.entries.length > 0) {
          sections.push(section)
          section = null
          state = 'list'
        } else fail()
        break
      case 'entries':
        if (line === 'GuideEntry(') {
          entry = { strings: [], combo: null, line: lineNo }
          state = 'entry'
        } else if (line === '),') state = 'section'
        else fail()
        break
      case 'entry': {
        const combo = /^combo = (".*"),$/.exec(line)
        if (combo) {
          if (entry.combo !== null) fail()
          entry.combo = literal(combo[1], lineNo)
        } else if (line.startsWith('"') && line.endsWith('",')) {
          if (entry.combo !== null) fail()
          entry.strings.push(literal(line.slice(0, -1), lineNo))
        } else if (line === '),') {
          const [action, keys, source, note, ...extra] = entry.strings
          if (source === undefined || extra.length > 0) {
            throw new Error(`GuideText.kt:${entry.line}: GuideEntry needs 3 or 4 positional strings, found ${entry.strings.length}`)
          }
          section.entries.push({ action, keys, source, note: note ?? null, combo: entry.combo })
          entry = null
          state = 'entries'
        } else fail()
        break
      }
    }
  }
  if (state !== 'done') throw new Error('GuideText.kt: the sections list is not closed')
  return sections
}

const q = (s) => (s === null ? 'null' : JSON.stringify(s))

export function render(sections) {
  const out = [
    `// Port of ${KT_PATH} (the \`sections\` data)`,
    '// Generated by web/scripts/gen-guide-data.mjs (npm run gen:guide). Do not edit by hand.',
    '',
    "import type { GuideSection } from './guideText'",
    '',
    'export const sections: readonly GuideSection[] = [',
  ]
  for (const s of sections) {
    out.push('  {', `    title: ${q(s.title)},`, '    entries: [')
    for (const e of s.entries) {
      out.push(
        '      {',
        `        action: ${q(e.action)},`,
        `        keys: ${q(e.keys)},`,
        `        source: ${q(e.source)},`,
        `        note: ${q(e.note)},`,
        `        combo: ${q(e.combo)},`,
        '      },',
      )
    }
    out.push('    ],', '  },')
  }
  out.push(']', '')
  return out.join('\n')
}

const isMain = process.argv[1] !== undefined && fileURLToPath(import.meta.url) === process.argv[1]
if (isMain) {
  const ts = render(parseGuide(readFileSync(ktFile, 'utf8')))
  if (process.argv.includes('--stdout')) process.stdout.write(ts)
  else writeFileSync(outFile, ts)
}
